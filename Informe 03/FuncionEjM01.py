def area_triangulo(base, altura):
    return (base * altura) / 2

par1 = area_triangulo(5, 3)
par2 = area_triangulo(10, 7)
par3 = area_triangulo(8, 4)

print("Triángulo 1 - Base: 5, Altura: 3 → Área:", par1)
print("Triángulo 2 - Base: 10, Altura: 7 → Área:", par2)
print("Triángulo 3 - Base: 8, Altura: 4 → Área:", par3)