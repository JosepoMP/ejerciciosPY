# Algoritmo: Calificacion
# Calcula si un alumno está aprobado o reprobado según su calificación

# --- Entrada ---
calificacion = float(input("Ingrese la calificacion del alumno: "))

# --- Proceso y Salida ---
if calificacion >= 8:
    print("El alumno está APROBADO")
else:
    print("El alumno está REPROBADO")
